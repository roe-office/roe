/// 预设名对应的点阵，未知名字退回 pct50。
pub fn tile(name: &str) -> [u8; 8] {
    let find = |n: &str| TILES.iter().find(|(k, _)| *k == n).map(|(_, t)| *t);
    find(name).or_else(|| find("pct50")).unwrap_or([0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55])
}

/// 点阵里 (x, y) 格是否为前景。
pub fn is_fg(t: &[u8; 8], x: usize, y: usize) -> bool {
    t[y % 8] & (0x80 >> (x % 8)) != 0
}

/// 生成 8x8 的预乘 RGBA 字节（256 字节），可直接交给 tiny-skia 的 Pixmap。
pub fn tile_premul_rgba(name: &str, fg: (u8, u8, u8, u8), bg: (u8, u8, u8, u8)) -> Vec<u8> {
    let t = tile(name);
    let pm = |c: (u8, u8, u8, u8)| {
        let a = c.3 as u32;
        let m = |v: u8| ((v as u32 * a + 127) / 255) as u8;
        [m(c.0), m(c.1), m(c.2), c.3]
    };
    let (f, b) = (pm(fg), pm(bg));
    let mut out = Vec::with_capacity(256);
    for y in 0..8 {
        for x in 0..8 {
            out.extend_from_slice(if is_fg(&t, x, y) { &f } else { &b });
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn has_54_unique_names() {
        let mut names: Vec<&str> = TILES.iter().map(|(n, _)| *n).collect();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), 54);
    }

    #[test]
    fn percent_tiles_get_denser() {
        let share = |n: &str| (0..64).filter(|i| is_fg(&tile(n), i % 8, i / 8)).count();
        let names = ["pct5", "pct10", "pct20", "pct25", "pct30", "pct40", "pct50", "pct60", "pct70", "pct75", "pct80", "pct90"];
        assert!(names.windows(2).all(|w| share(w[0]) <= share(w[1])));
    }

    #[test]
    fn unknown_name_falls_back_and_rgba_len() {
        assert_eq!(tile("nonsense"), tile("pct50"));
        assert_eq!(tile_premul_rgba("pct50", (0, 0, 0, 255), (255, 255, 255, 255)).len(), 256);
    }
}
